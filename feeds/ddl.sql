CREATE TABLE rss_sources (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    title       TEXT    NOT NULL,
    xml_url     TEXT    NOT NULL UNIQUE,
    html_url    TEXT,
    source_type TEXT    NOT NULL CHECK(source_type IN ('企业','个人','机构')),
    tier        TEXT    NOT NULL CHECK(tier IN ('T0','T1','T2','T3','T4')),
    stars       INTEGER NOT NULL CHECK(stars BETWEEN 1 AND 5),
    tags        TEXT    DEFAULT '[]',
    language    TEXT    DEFAULT 'zh',
    description TEXT
);


CREATE TABLE role_source_map (
    role_id      INTEGER NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    source_id    INTEGER NOT NULL REFERENCES rss_sources(id) ON DELETE CASCADE,
    priority     TEXT    NOT NULL DEFAULT '选配' CHECK(priority IN ('必选','选配')),
    match_reason TEXT,
    PRIMARY KEY (role_id, source_id)
);
CREATE INDEX idx_rsm_source ON role_source_map(source_id);

-- 常用筛选字段索引
CREATE INDEX idx_source_type ON rss_sources(source_type);
CREATE INDEX idx_tier        ON rss_sources(tier);
CREATE INDEX idx_language    ON rss_sources(language);
CREATE INDEX idx_rsm_role    ON role_source_map(role_id, priority);
